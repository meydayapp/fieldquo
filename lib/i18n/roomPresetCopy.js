// lib/i18n/roomPresetCopy.js
//
// Every word of the interior-painting ROOM PICKER — the homeowner's form, the
// panel beside it, the report rows and the draft's line labels — in all nine
// catalogue languages (en fr es it de uk pa tl zh).
//
// ── Why a table of its own and not more keys in instantQuoteCopy ───────────
//
// instantQuoteCopy is the page's own table and carries three languages, the
// three the instant form offers today (INSTANT_QUOTE_LANGUAGES). The room
// picker's words also land on the DRAFT — line labels, the "typical size,
// confirm on site" detail, the assumption the reviewer reads — and a draft
// keeps the language it was created in (non-negotiable #6). The day the
// form offers Italian or Punjabi, a picker that only spoke three languages
// would write English lines onto an Italian quote. So the picker speaks all
// nine now, and the page simply asks it for whichever of them it is in.
//
// Same arrangement as instantQuoteCopy: hand-written transactional strings,
// functions where a value is interpolated, no imports, so the browser, the
// routes, the pure estimator and the check scripts all read it.
//
// The words for "typical size, confirm on site" are the load-bearing ones:
// they are what keeps a size the homeowner never measured from reading as a
// measurement anywhere it lands (AGENTS.md recurring failure 5 — absence of a
// statement is not a statement; the stairs rule says "estimated from 14
// steps" for the same reason).

