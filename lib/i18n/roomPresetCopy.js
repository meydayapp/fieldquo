/** The two-letter code when it is one of the nine, else null. */
export function roomCopyLanguage(value) {
  const code = String(value || "").toLowerCase().slice(0, 2);
  return ROOM_COPY_LANGUAGES.includes(code) ? code : null;
}

/** The picker's words in a language; English for anything that is not one of the nine. */
export function roomCopy(language = "en") {
  return COPY[roomCopyLanguage(language) || "en"];
}

/** The number-formatting locale for a language. */
export function roomCopyLocale(language = "en") {
  return LOCALES[roomCopyLanguage(language) || "en"];
}

