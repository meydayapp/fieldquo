// lib/i18n/instantQuoteCopy.js
//
// Every visible string on the public instant-estimate page
// (app/instant-quote/[companySlug]/InstantQuoteFlow.js) and the server
// sentences it echoes, in the eight product languages (app/i18n/languages.js
// LANGUAGE_CODES): English, French, Spanish, Ukrainian, Punjabi, Tagalog,
// German and Italian. Until 2026-10-03 it carried the first three only; the
// owner extended it to all eight and gave each company the choice of which
// ones its form offers (lib/estimate/instantQuoteLanguages.js).
//
// ── Why one table and not the ternaries it replaces ────────────────────────
//
// The page used to carry its copy as `fr ? "…" : "…"` scattered through
// 1,400 lines of JSX. Two things followed from that: Spanish did not exist
// (a Spanish company's homeowners got English), and every string the
// ternary forgot stayed English inside a French page — the section titles,
// the field labels, the "still needed" list, the whole junk-removal picker.
// A stranger in a driveway reading "Tell us about the property" under a
// French headline concludes the contractor is not really French-speaking,
// which is the white-label promise broken on the surface that wins the job.
//
// The visitor picks the language on the page (the pills the company
// offers), and non-
// negotiable #6 makes that choice the DOCUMENT's language: the draft, the
// lead and the confirmation email are created in it and never re-translated.
//
// Same arrangement as lawnEstimateCopy / gutterEstimateCopy: a closed set of
// hand-written transactional strings, functions where a value is
// interpolated, and no imports — the browser, the routes and the check
// script all read it. Labels for the lawn cards and the "doesn't look right"
// control stay in lawnEstimateCopy, which this table does not duplicate.

/**
 * Every language the form CAN be read in, in the order the pills are drawn.
 *
 * The order is app/i18n/languages.js LANGUAGES' (the check script pins the
 * two), not a ranking of its own: the settings card, the app's own language
 * picker and the client-language selectors all draw that order, so a
 * contractor ticking boxes and a homeowner reading pills see one sequence
 * everywhere. It also keeps en/fr/es first, so the three pills every live
 * form already draws do not move. Listed here rather than imported because
 * this file imports nothing (the browser, the routes and the check script
 * all read it).
 */
export const INSTANT_QUOTE_LANGUAGES = ["en", "fr", "es", "uk", "pa", "tl", "de", "it"];

/**
 * What a company that never chose offers: exactly the three every form drew
 * before the other five existed. lib/estimate/instantQuoteLanguages.js says
 * why "never chose" keeps today's form rather than becoming all eight.
 */
export const INSTANT_QUOTE_DEFAULT_LANGUAGES = ["en", "fr", "es"];

/**
 * A posted / queried language, or null when it is not one of the eight.
 * "fr-CA" → fr, "pa-IN" → pa; browsers report Tagalog as Filipino ("fil",
 * "fil-PH") far more often than as "tl", so that one alias is mapped, the
 * same as lib/i18n/statedLanguage.js deviceLanguage does.
 */
export function instantQuoteLanguage(value) {
  const base = String(value || "").trim().toLowerCase().split(/[-_]/)[0];
  const code = base === "fil" ? "tl" : base.slice(0, 2);
  return INSTANT_QUOTE_LANGUAGES.includes(code) ? code : null;
}

