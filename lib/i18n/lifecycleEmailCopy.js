const COPY = Object.freeze({ en, fr, es, it, de, uk, pa, tl, zh });

/** Exported for scripts/check-lifecycle-emails.mjs's completeness proof. */
export const LIFECYCLE_COPY = COPY;
export const LIFECYCLE_COPY_KEYS = Object.freeze(Object.keys(en));

/** The reader's language as one of the nine, English otherwise ("fr-CA" → "fr"). */
export function lifecycleLanguage(code) {
  const short = String(code || "").toLowerCase().split(/[-_]/)[0];
  return LIFECYCLE_LANGUAGES.includes(short) ? short : "en";
}

/**
 * t(key, values) in one language, falling back PER KEY to English — never to
 * the key itself in a sent email: an unknown key throws, because a letter
 * with "nudge.payments.subject" in its subject line has already gone out by
 * the time anybody reads the log.
 */
export function lifecycleT(language) {
  const lang = lifecycleLanguage(language);
  const dict = COPY[lang] || en;
  return (key, values = {}) => {
    const raw = dict[key] ?? en[key];
    if (raw === undefined) throw new Error(`lifecycleEmailCopy: no sentence for "${key}"`);
    return String(raw).replace(/\{(\w+)\}/g, (m, k) => (values[k] !== undefined && values[k] !== null ? String(values[k]) : m));
  };
}
