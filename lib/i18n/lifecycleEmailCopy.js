// Every sentence FieldQuo's own lifecycle emails print to a CONTRACTOR — the
// shared layout's chrome (lib/email/platformLayout.js), the email-preferences
// page, and the trial sequence (lib/lifecycle/emails.js) — in the nine app
// languages (app/i18n/appMessages.js APP_MESSAGES: en fr es uk pa tl de zh it).
//
// ── Why a module of its own, not more keys in appMessages.js ──────────────
//
// appMessages.js is 170,000 lines that every app screen edits, and on
// 2026-10-11 two agents were writing lifecycle emails into it at once. A
// self-contained table also lets scripts/check-lifecycle-emails.mjs prove
// completeness the simple way: every language carries every English key,
// with exactly the same {placeholders}, and no value is the English one
// copied across (a few brand words excepted). The four letters that existed
// before keep their app.* keys — their wording does not move.
//
// ── What the sentences may claim ───────────────────────────────────────────
//
// Only what the product does today, checked against the code it describes:
//   - card payments: Stripe Connect, a Pay button on every invoice
//     (lib/onboarding.js "payments" step, stripeChargesEnabled);
//   - pay over time: Klarna / Affirm only where Stripe activated them, the
//     provider decides approval and the client repays it (the sources are
//     cited in lib/payments/payOverTimeGuide.js — never a rate, never "0%");
//   - follow-ups: the "quote sent, no response" rule (Settings › Follow-ups);
//   - the client portal: approve, sign and pay from one link;
//   - read-only then locked, nothing deleted (lib/billing/access.js).
//
// Reviewed by nobody but their author outside English and French — the same
// standing as the rest of the review-pending catalogues (APP_REVIEW_PENDING).
// Never machine-translated at send time: a missing key falls back to English
// per key, at build time, and the check refuses a missing key anyway.

