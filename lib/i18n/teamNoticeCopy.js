// ── Nine languages, because the reader is staff ────────────────────────────
//
// A client can be written to in the eight document languages
// (lib/i18n/emailCopy.js). A notice to staff is written in the READER's
// interface language (lib/i18n/letterLanguage.js: User.language, then
// Company.defaultLanguage, then English), and the interface has nine — zh is
// an app language with no client documents. So this table carries zh too.
//
// ── The English is the old English ─────────────────────────────────────────
//
// Until 2026-10-13 these notices were English-only one-line HTML in the
// routes that sent them. The English sentences below are those lines, word
// for word (scripts/check-team-notices.mjs holds the old sentences and fails
// if one stops appearing). What is new is only the furniture the owner asked
// for — headings, the facts card's labels, the button words, and the one
// small-print line that says where a switchable alert is switched off.
//
// Hand-written, closed, never drafted at send time; held key-for-key with
// English by scripts/check-language-completeness.mjs (TABLES).

