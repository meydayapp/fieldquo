// lib/designer/templateCopy.js
//
// The words printed ON a catalogue template (lib/designer/templateCatalog.js),
// in every language the app speaks.
//
// ── Why these are not in app/i18n/appMessages.js ───────────────────────────
//
// Those are interface strings, chosen by the person using the screen. These
// are the words that go out on a post under the contractor's name, so they
// are written in the COMPANY's language (Company.defaultLanguage) at the
// moment a template is applied — and then they are the design's own text,
// never re-translated. Non-negotiable #6 applied to a post: a thing keeps the
// language it was made in. A French-speaking owner and an English-speaking
// office manager applying the same template get the same post.
//
// ── What is sample copy and what is a placeholder ──────────────────────────
//
// Plain entries ("Free estimates") are generic trade copy anybody may post
// as-is — they state no fact about the company. `ph.*` entries are bracketed
// placeholders for things only the company knows: a review, a number, a
// licence, their town when it has never been entered. lib/designer/
// placeholders.js tags the objects carrying them, and both publish routes
// refuse while one is still on the design — a template must never put an
// invented review or statistic in front of the public.
//
// Tokens in braces are filled from the company's own row by
// lib/designer/templateFill.js; a token with no data behind it becomes the
// matching `ph.*` text, never a guess.

