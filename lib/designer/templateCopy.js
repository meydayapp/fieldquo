export const TEMPLATE_COPY = { en, fr, es, uk, pa, tl, de, zh, it };

/** A language this module has, else English — never a blank string. */
export function copyLanguage(language) {
  const code = String(language || "en").toLowerCase().slice(0, 2);
  return Object.prototype.hasOwnProperty.call(TEMPLATE_COPY, code) ? code : "en";
}

/** One string, in `language`, falling back to English for a missing key. */
export function copyFor(key, language) {
  const dict = TEMPLATE_COPY[copyLanguage(language)];
  return (dict && dict[key]) || en[key] || "";
}
