// The help centre's CHROME — nav, category names, buttons, notices — in every
// language the app speaks (the nine of app/i18n/appMessages.js).
//
// ── Why its own catalogue and not app.* keys ───────────────────────────────
//
// The bodies of articles exist in English, French and Spanish (written, not
// machine-translated — see content/help/). A Ukrainian or Punjabi reader
// still gets the whole frame in their language plus an honest one-line
// notice that the article itself is English for now; that frame is what this
// file carries. It is kept beside the help centre rather than inside
// app/i18n/appMessages.js because the help centre is a PUBLIC surface
// rendered on the server with no LanguageProvider, and because appMessages
// is the /app interface catalogue, gated by its own coverage floors — a
// separate surface's strings belong in a separate file that
// scripts/check-help-centre.mjs holds to the same rule: every key, every
// language, no English fallback that goes unreported.
//
// Every language block must carry every key `en` has; the check fails
// otherwise. A missing key would silently fall back to English, which is the
// exact "control that appears to work" AGENTS.md warns about.

