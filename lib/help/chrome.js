export const HELP_CHROME = Object.freeze({ en, fr, es, uk, pa, tl, de, zh, it });
export const HELP_CHROME_LANGS = Object.freeze(Object.keys(HELP_CHROME));
export const HELP_CHROME_KEYS = Object.freeze(Object.keys(en));

/** The chrome strings for a language, falling back to English per key. */
export function helpT(lang) {
  const dict = HELP_CHROME[lang] || en;
  return (key, vars = null) => {
    let s = typeof dict[key] === "string" ? dict[key] : en[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
    return s;
  };
}

/** Is this a language the help centre renders chrome for? */
export function isHelpChromeLang(lang) {
  return Object.prototype.hasOwnProperty.call(HELP_CHROME, lang);
}
