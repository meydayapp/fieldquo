// What a quote SAYS about each trade — in Ukrainian ("uk", not British English).
//
// ── Why a parallel file, and not translation at send time ───────────────────
//
// A document keeps the language it was created in (AGENTS.md non-negotiable
// #6). The prose here is not stored on the quote; resolveServiceContent picks
// it at render time from a STATIC catalogue keyed by the quote's own fixed
// `language`, so a Ukrainian quote renders the same sentences on the day it is
// signed and on every day after. Nothing is machine-translated at send time,
// and a viewer's browser language changes nothing.
//
// The readers are Ukrainian-speaking homeowners in Canada and the US, so a
// North-American building element with no Ukrainian equivalent is named by
// the Ukrainian trade word (ринва, лобова дошка, софіт, гіпсокартон) or a
// plain descriptive phrase, never left in English.
//
// Same rules as the English: nothing states a warranty term, a price, a cure
// time, a brand or a number of days that the English does not. Anything
// specific stays a [placeholder] — in Ukrainian, and still in square
// brackets, because the resolver withholds a line with a bracket left in it
// whatever language the bracket is in. Keys and shape mirror
// lib/documents/serviceContent.js; text fields only (no `accent`, no
// `variantOn` — those ride through from the English).

