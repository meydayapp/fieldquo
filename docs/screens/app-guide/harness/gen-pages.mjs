// Emits pages.gen.jsx: one static import per distinct page module in
// screens.js, so the bundle carries every screen and guide.jsx picks one at
// runtime by ?page=. Generated rather than hand-kept so a screen added to
// screens.js cannot be forgotten here.
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { SCREENS } from "./screens.js";
const here = dirname(fileURLToPath(import.meta.url));
const mods = [...new Set(SCREENS.map((s) => s.page))];
const lines = ["// GENERATED by gen-pages.mjs — do not edit.", ...mods.map((m, i) => `import P${i} from "@/${m}";`), "export const PAGES = {", ...mods.map((m, i) => `  ${JSON.stringify(m)}: P${i},`), "};", ""];
writeFileSync(join(here, "pages.gen.jsx"), lines.join("\n"));
console.log(`pages.gen.jsx: ${mods.length} page modules`);
