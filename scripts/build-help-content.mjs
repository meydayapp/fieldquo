// scripts/build-help-content.mjs
//
//   node scripts/build-help-content.mjs          # npm run build:help
//
// Everything the help centre needs that is not a page: run before `next
// build` (it is the first step of `npm run build`) and by hand after editing
// an article.
//
//   1. content/help/index.js — the lazy loader map, regenerated from
//      lib/help/tree.js so a new category cannot be forgotten.
//   2. public/help/figures/<lang>/<kind>-<name>.png — every screenshot an
//      article references, copied from the capture sets lib/help/figures.js
//      names. Only referenced files are copied, so public/ carries what the
//      pages show and nothing else; public/help is gitignored because the
//      sources are already in the repo under docs/screens.
//   3. content/help/figures.generated.json — which capture LANGUAGE answered
//      each figure per body language, so the page can say "Screen shown in
//      English" under a French article's English capture instead of leaving
//      the reader to notice.
//   4. public/help/search/<lang>.json — the client-side search index: title,
//      summary, headings and the first paragraphs of every written article.
//      One per chrome language; the six languages without bodies index the
//      English body, which is what they read.
//   5. content/help/TREE.md — the coverage table between its markers, for
//      the owner's review.
//
// Tolerant where the CHECK is strict: an article not yet written in a
// language is reported and skipped (a deploy mid-writing must not fail), but
// a referenced figure that no capture set answers FAILS — that would be a
// broken image on a published page, and there is no honest fallback for it.
import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync, copyFileSync, rmSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { HELP_LANGS, HELP_TREE, HELP_ARTICLES, REAL_CATEGORY_KEYS } from "../lib/help/tree.js";
import { HELP_CHROME_LANGS } from "../lib/help/chrome.js";
import { resolveFigure } from "./help-figure-sources.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const CONTENT = join(ROOT, "content/help");
const PUBLIC = join(ROOT, "public/help");

// ── 1. The loader index ────────────────────────────────────────────────────
{
  let out = `// content/help/index.js\n//\n// GENERATED by scripts/build-help-content.mjs from lib/help/tree.js — do not\n// edit by hand. One lazy loader per language per category, so a page imports\n// only the module it renders and Next can bundle each one statically.\n\nexport const LOADERS = {\n`;
  for (const lang of HELP_LANGS) {
    out += `  ${lang}: {\n`;
    // Assembled from pieces so scripts/check-imports.mjs — which greps for
    // `import("…")` and cannot resolve a computed specifier — does not read
    // this template as an import of its own.
    for (const c of REAL_CATEGORY_KEYS) out += `    "${c}": () => ${"import"}("./${lang}/${c}.js"),\n`;
    out += `  },\n`;
  }
  out += `};\n`;
  writeFileSync(join(CONTENT, "index.js"), out);
}

// ── Load every module ──────────────────────────────────────────────────────
const modules = {}; // modules[lang][category] = ARTICLES
const unwritten = [];
for (const lang of HELP_LANGS) {
  modules[lang] = {};
  for (const category of REAL_CATEGORY_KEYS) {
    const file = join(CONTENT, lang, `${category}.js`);
    if (!existsSync(file)) {
      writeFileSync(
        file,
        `// content/help/${lang}/${category}.js\n//\n// Articles of the “${category}” category in ${lang}. Keyed by slug; the slugs are\n// listed in lib/help/tree.js and scripts/check-help-centre.mjs refuses a\n// module that is missing one or carries one the tree does not.\n// Not written yet.\nexport const ARTICLES = {};\n`,
      );
    }
    const mod = await import(`${file}?t=${Date.now()}`);
    modules[lang][category] = mod.ARTICLES || {};
    for (const a of HELP_TREE[category]) if (!modules[lang][category][a.slug]) unwritten.push(`${lang}/${category}/${a.slug}`);
  }
}

// ── 2 + 3. Figures ─────────────────────────────────────────────────────────
function* figureRefs(article) {
  for (const s of article.sections || []) for (const b of s.blocks || []) if (typeof b?.figure === "string") yield b.figure;
}

const figureMap = {};
const missingFigures = [];
const figureStats = {};
if (existsSync(join(PUBLIC, "figures"))) rmSync(join(PUBLIC, "figures"), { recursive: true });
for (const lang of HELP_LANGS) {
  figureMap[lang] = {};
  figureStats[lang] = { copied: 0, fellBack: 0 };
  const dir = join(PUBLIC, "figures", lang);
  mkdirSync(dir, { recursive: true });
  for (const category of REAL_CATEGORY_KEYS) {
    for (const [slug, article] of Object.entries(modules[lang][category])) {
      for (const ref of figureRefs(article)) {
        const hit = resolveFigure(ref, lang);
        if (!hit) {
          missingFigures.push(`${lang}/${category}/${slug}: ${ref}`);
          continue;
        }
        const dest = join(dir, `${hit.publicName}.png`);
        if (!existsSync(dest)) {
          copyFileSync(hit.file, dest);
          figureStats[lang].copied++;
          if (hit.lang !== lang) figureStats[lang].fellBack++;
        }
        figureMap[lang][hit.publicName] = hit.lang;
      }
    }
  }
}
writeFileSync(join(CONTENT, "figures.generated.js"), `// GENERATED by scripts/build-help-content.mjs — which capture language answered\n// each figure, per body language. Do not edit.\nexport const FIGURE_SOURCES = ${JSON.stringify(figureMap, null, 2)};\n`);

// The owner's videos.json, as a module the pages can import (see lib/help/content.js).
{
  const videos = JSON.parse(readFileSync(join(CONTENT, "videos.json"), "utf8"));
  writeFileSync(join(CONTENT, "videos.generated.js"), `// GENERATED by scripts/build-help-content.mjs from content/help/videos.json —\n// edit THAT file, then run npm run build:help. Do not edit this one.\nexport const VIDEOS = ${JSON.stringify(videos, null, 2)};\n`);
}

// ── 4. Search index ────────────────────────────────────────────────────────
const plain = (s) => String(s || "").replace(/\[\[[a-z0-9-]+\|([^\]]+)\]\]/g, "$1").replace(/\*\*/g, "");
mkdirSync(join(PUBLIC, "search"), { recursive: true });
const indexSizes = {};
for (const lang of HELP_CHROME_LANGS) {
  const bodyLang = HELP_LANGS.includes(lang) ? lang : "en";
  const rows = [];
  for (const category of REAL_CATEGORY_KEYS) {
    for (const meta of HELP_TREE[category]) {
      const a = modules[bodyLang][category][meta.slug];
      if (!a) continue;
      const firstParas = [];
      for (const p of a.intro || []) firstParas.push(plain(p));
      for (const s of a.sections || []) {
        const p = (s.blocks || []).find((b) => typeof b?.p === "string");
        if (p) firstParas.push(plain(p.p));
      }
      rows.push({
        slug: meta.slug,
        category,
        title: plain(a.title),
        summary: plain(a.summary),
        headings: (a.sections || []).map((s) => plain(s.heading)),
        body: firstParas.join(" ").slice(0, 700),
      });
    }
  }
  const json = JSON.stringify(rows);
  writeFileSync(join(PUBLIC, "search", `${lang}.json`), json);
  indexSizes[lang] = json.length;
}

// ── 5. The coverage table in TREE.md ───────────────────────────────────────
{
  const file = join(CONTENT, "TREE.md");
  const START = "<!-- tree:start -->";
  const END = "<!-- tree:end -->";
  const written = (lang, category, slug) => Boolean(modules[lang]?.[category]?.[slug]);
  const rows = [];
  let total = 0;
  for (const category of REAL_CATEGORY_KEYS) {
    const list = HELP_TREE[category];
    total += list.length;
    rows.push(`\n### ${category} (${list.length})\n`);
    rows.push(`| Article | en | fr | es | Screen | Feature | Only |`);
    rows.push(`|---|:-:|:-:|:-:|---|---|:-:|`);
    for (const a of list) {
      const title = modules.en[category][a.slug]?.title || a.title;
      rows.push(
        `| \`${a.slug}\` — ${title} | ${written("en", category, a.slug) ? "✓" : "·"} | ${written("fr", category, a.slug) ? "✓" : "·"} | ${written("es", category, a.slug) ? "✓" : "·"} | ${a.screen || ""} | ${a.feature || (a.proof ? "proof" : "")} | ${a.only ? "✓" : ""} |`,
      );
    }
  }
  const writtenCount = Object.fromEntries(HELP_LANGS.map((l) => [l, HELP_ARTICLES.filter((a) => written(l, a.category, a.slug)).length]));
  const block = `${START}\n\n_Generated ${new Date().toISOString().slice(0, 10)} — ${total} articles in the tree; written: en ${writtenCount.en}, fr ${writtenCount.fr}, es ${writtenCount.es}; “Only in FieldQuo”: ${HELP_ARTICLES.filter((a) => a.only).length}._\n${rows.join("\n")}\n\n${END}`;
  const existing = existsSync(file) ? readFileSync(file, "utf8") : `# The help-centre tree\n\n${START}\n${END}\n`;
  const s = existing.indexOf(START);
  const e = existing.indexOf(END);
  const next = s >= 0 && e > s ? existing.slice(0, s) + block + existing.slice(e + END.length) : `${existing}\n${block}\n`;
  writeFileSync(file, next);
}

// ── Report ─────────────────────────────────────────────────────────────────
for (const lang of HELP_LANGS) {
  console.log(`help: ${lang} — ${figureStats[lang].copied} figures copied (${figureStats[lang].fellBack} English fallbacks), search index ${(indexSizes[lang] / 1024).toFixed(0)} KB`);
}
if (unwritten.length) console.log(`help: ${unwritten.length} article(s) not written yet (check:help-centre lists them)`);
if (missingFigures.length) {
  console.error(`help: ${missingFigures.length} figure reference(s) no capture set answers — these would be broken images:\n  ${missingFigures.join("\n  ")}`);
  process.exit(1);
}
