#!/usr/bin/env node
//
// scripts/gen-interconnections.mjs
//
// Generates the entity map in docs/INTERCONNECTIONS.md from prisma/schema.prisma.
//
// GENERATED, not written. A hand-drawn dependency map is a snapshot of what
// somebody believed on the day they drew it, and this repo has three features
// from one week that were built at the wrong end of a flow. The relations ARE
// the graph; anything else is a second opinion that drifts.
import { readFileSync, writeFileSync } from "node:fs";

const schema = readFileSync("prisma/schema.prisma", "utf8");

// ── Parse ────────────────────────────────────────────────────────────────
// Deliberately crude: this reads one repo's own schema, not arbitrary Prisma.
const models = new Map();
const modelRe = /^model\s+(\w+)\s*\{([\s\S]*?)^\}/gm;
let m;
while ((m = modelRe.exec(schema))) {
  const [, name, body] = m;
  const fields = [];
  for (const raw of body.split("\n")) {
    const line = raw.trim();
    if (!line || line.startsWith("//") || line.startsWith("///") || line.startsWith("@@")) continue;
    const f = line.match(/^(\w+)\s+(\w+)(\[\])?(\?)?/);
    if (!f) continue;
    fields.push({ name: f[1], type: f[2], list: Boolean(f[3]), optional: Boolean(f[4]) });
  }
  models.set(name, fields);
}

const isModel = (t) => models.has(t);

// Outgoing = this model points at that one. Incoming = that one points here.
const out = new Map(), inc = new Map();
for (const [name, fields] of models) {
  out.set(name, new Set());
  if (!inc.has(name)) inc.set(name, new Set());
}
for (const [name, fields] of models) {
  for (const f of fields) {
    if (!isModel(f.type) || f.type === name) continue;
    if (f.list) {
      // A list is the far side of someone else's foreign key — it tells us
      // they point here, which `inc` already records from their side.
      continue;
    }
    out.get(name).add(f.type);
    if (!inc.has(f.type)) inc.set(f.type, new Set());
    inc.get(f.type).add(name);
  }
}

// ── The hubs ─────────────────────────────────────────────────────────────
// Ranked by how many models point AT them. Those are the things you cannot
// change without touching everything, and the ones people duplicate because
// they did not know they existed.
const hubs = [...inc.entries()]
  .map(([name, set]) => ({ name, count: set.size, from: [...set].sort() }))
  .filter((h) => h.count > 0)
  .sort((a, b) => b.count - a.count || a.name.localeCompare(b.name));

const skip = new Set(["Company", "User", "Session", "Account", "Verification"]);

let doc = `<!-- GENERATED by scripts/gen-interconnections.mjs — do not hand-edit this section -->

## The entity graph

Every model, and what points at it. Generated from \`prisma/schema.prisma\`, so
it cannot drift from the code. ${models.size} models.

**Read it before adding anything.** The question it answers is "what already
touches this, and what would my change touch" — which is the question that was
not asked before a change order reached no invoice, before phone hours reached
no job, and before a receipt was aimed at a table nothing reads.

\`Company\` is omitted from the hub list: nearly everything hangs off it by
tenancy, so it carries no information.

### The hubs — what everything attaches to

| Entity | Pointed at by | From |
|---|---:|---|
`;

for (const h of hubs.filter((x) => !skip.has(x.name)).slice(0, 18)) {
  doc += `| **${h.name}** | ${h.count} | ${h.from.slice(0, 10).join(", ")}${h.from.length > 10 ? ` +${h.from.length - 10}` : ""} |\n`;
}

doc += `
### Every model, both directions

<details><summary>${models.size} models — expand</summary>

| Model | Points at | Pointed at by |
|---|---|---|
`;
for (const name of [...models.keys()].sort()) {
  const o = [...(out.get(name) || [])].filter((x) => !skip.has(x)).sort();
  const i = [...(inc.get(name) || [])].sort();
  if (!o.length && !i.length) continue;
  doc += `| \`${name}\` | ${o.join(", ") || "—"} | ${i.join(", ") || "—"} |\n`;
}
doc += "\n</details>\n";

writeFileSync("docs/INTERCONNECTIONS.generated.md", doc);

// Also emit the raw graph, so a visualiser reads the same source of truth the
// document does rather than a second hand-maintained copy.
const nodes = [...models.keys()].map((name) => ({
  id: name,
  in: (inc.get(name) || new Set()).size,
  out: [...(out.get(name) || [])].filter((x) => x !== "Company").length,
}));
const edges = [];
for (const [name, set] of out) {
  for (const target of set) edges.push([name, target]);
}
writeFileSync("docs/interconnections.json", JSON.stringify({ nodes, edges }, null, 0));
console.log(`Generated: ${models.size} models, ${hubs.length} with inbound relations.`);
console.log("\nTop hubs:");
for (const h of hubs.filter((x) => !skip.has(x.name)).slice(0, 12)) {
  console.log(`  ${String(h.count).padStart(3)}  ${h.name}`);
}
