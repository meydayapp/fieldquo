// scripts/build-reverse-selling-doc.mjs
//
//   npm run build:reverse-selling-doc
//
// Writes docs/sales/REVERSE-SELLING-SCRIPTS.md — the Reverse Selling scripts,
// in the version the code is at, as the owner copies them into his own document — FROM the code
// the reps' screens read: lib/sales/playbook/reverseSelling.js (the nine
// stages and the short objection answers), lib/sales/playbook/
// reverseSellingScripts.js (one script per lead source, the follow-ups, the
// demo, the check-ins, the partner call, the Backup), lib/sales/calls/qa.js
// (the coach's weights). Generated rather than retyped so the document and
// the screens cannot say two different things; check:reverse-selling-playbook
// fails when they drift, and this is the command that fixes it.
//
// No model, no database: the db stub keeps lib/referrals' import inert.
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { TRIAL_CARD_REQUIRED, TRIAL_DAYS } from "@/lib/pricing";
import { REP_DEMO_MINUTES } from "@/lib/sales/demoBooking/slots";
import { STAGES } from "@/lib/sales/playbook/stages";
import {
  REVERSE_SELLING_VERSION,
  seedReverseSellingObjections,
  seedReverseSellingPlaybook,
} from "@/lib/sales/playbook/reverseSelling";
import { reverseSellingScripts } from "@/lib/sales/playbook/reverseSellingScripts";
import { REVERSE_SELLING_WEIGHTS } from "@/lib/sales/calls/qa";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "docs/sales/REVERSE-SELLING-SCRIPTS.md");

const PB = seedReverseSellingPlaybook();
const OBJ = seedReverseSellingObjections();
const SCRIPTS = reverseSellingScripts();

const GROUP_TITLES = {
  lead_source: "Scripts by where the lead came from",
  follow_up: "Follow-up calls",
  demo: "The demo",
  check_in: "Customer check-ins through the year",
  partner: "Referral partners",
  backup: "Backup — the long answers (version 1, word for word)",
};

const COACH = {
  demoBooked: "Demo booked (or a trial the contractor asked for)",
  twoChoiceTime: "Time offered as two choices, not \"what time works?\"",
  minimalDiscovery: "Discovery kept to two questions",
  objectionRedirect: "Objections answered short and redirected, never argued",
  gaveControl: "Control handed to the contractor",
  prepQuestions: "Prep questions once the demo is booked",
  referralAsk: "The referral question",
  noWhy: "No \"why\" questions",
};

const out = [];
const p = (...lines) => out.push(...lines);

p(
  "# Reverse Selling — the call scripts (version " + REVERSE_SELLING_VERSION + ")",
  "",
  "_Generated by `npm run build:reverse-selling-doc` from the code the reps' screens read. Do not edit by hand — edit `lib/sales/playbook/reverseSelling.js` or `reverseSellingScripts.js` and rebuild. `npm run check:reverse-selling-playbook` fails if this file and the code disagree._",
  "",
  "Our own words, written for trade contractors. Nothing here is taken from the book.",
  "",
  "## What changed (owner, 2026-10-02)",
  "",
  `- **The demo is ${REP_DEMO_MINUTES} minutes**, one number everywhere: the call panel's \"Book a demo\", the rep's demo page and its slots, the intro email, the signup opener, and every line below that offers the demo.`,
  "- **One script on the call screen.** The rep sees the one script for this lead's source, picked automatically — or the demo script when a demo with this lead is booked for today. No second script beside it.",
  "- **One cold call.** Versions 1.0 and 2.0 are merged into one, based on 1.0; 2.0's \"who else would want a say\" is now part of the booking line.",
  "- **Every prospect gets it once it is on**, including a business nothing has been recorded about yet (they used to fall through to the old AI script).",
  "",
  "## What changed (owner, 2026-10-01)",
  "",
  "- **The first call books a demo.** It does not close and does not push the free trial. The trial is started on the call only when the prospect asks for it or clearly wants it now.",
  "- **Short.** Each call script is six to ten lines, almost all questions.",
  "- **The opener is support, then they decide.** Who you are and the recording aside, \"I know you weren't expecting my call\", the owner's support line, and \"if it's worth a couple of minutes… you decide from there. Fair enough?\"",
  "- **Two discovery questions on the call:** what has them thinking about it, and when. The deep questions are the demo's.",
  "- **The call ends by booking:** two concrete choices of time, their email for the invite, a foreshadow of the meeting, then prep questions so the demo is about them.",
  "- **Objection answers are two to four sentences** and always move to the next step: agree, speak from their side, \"let's not decide anything now\" and the demo, what's in it for them, then \"you decide, either way it's no big deal, fair enough?\".",
  "- **The long answers are not deleted.** Stories, best case / worst case and \"let's play it out\" are the Backup, for the demo or a prospect who asks for more. The present, the cost questions, the reverse close and ask-resolve-ask moved into the demo.",
  "",
  "## Facts the scripts use, and where they come from",
  "",
  `- The demo: **${REP_DEMO_MINUTES} minutes** — \`REP_DEMO_MINUTES\` in \`lib/sales/demoBooking/slots.js\`, read from \`NEXT_STEP_MINUTES.demo\` in \`lib/sales/nextSteps.js\`: the block the call panel books, the slot the rep's demo page offers, and the length the intro email promises.`,
  `- The trial: **${TRIAL_DAYS} days**, ${TRIAL_CARD_REQUIRED ? "a card at signup" : "no card to start"} — \`TRIAL_DAYS\` / \`TRIAL_CARD_REQUIRED\` in \`lib/pricing.js\`.`,
  "- Plans, seats and crew: `SEAT_LADDER` in `lib/pricing/ladder.js`. Referral months: `lib/referrals` (the referrer's month lands when the referred company pays; the newcomer's extra trial month only through the referrer's own link).",
  "- Placeholders: `{businessName}`, `{repName}` and `{first}` are filled on the call screen where it knows them; `[day]`, `[time]` and `[their words]` are the rep's, from the calendar and the call notes. No line names a day.",
  "",
  "## Where a rep sees them",
  "",
  "- **The call screen** (a claimed prospect): ONE script — the one for this lead's source, picked automatically, or the demo script when a demo with this lead is booked for today (with a small \"Not the demo?\" switch back to the call script). A cold call carries a small \"Not a cold call?\" switch for the three sources nothing on the record marks: a customer's referral, a link sent and never used, and a call they made to us. Under the script, the short objection answers (tap to open), then one closed \"Tips\" area: this script's notes, what to do after a yes, and the notes for every stage.",
  "- The nine stages below stay the playbook's own data — the call coach, the AI script and the Playbook tab read them — but the call screen does not step through them.",
  "- **The Playbook tab** (/sales/playbook): all of it — the stages, every script, the follow-ups, the demo, the check-ins, the referral-partner call and the Backup — for reading before a call. Those are not on the call screen.",
  "- Both only while the Reverse Selling playbook is **switched on**. It is installed switched off; the owner switches it on in the platform console. Once on, it opens on every prospect, including one nothing has been recorded about yet.",
  "",
  "---",
  "",
  "## The cold call — the nine stages",
  "",
);

for (const def of STAGES) {
  const s = PB.stages.find((x) => x.stageKey === def.key);
  if (!s) continue;
  p(`### ${def.name}`, "");
  if (s.say) p(s.say, "");
  if (s.prompts.length) {
    for (const q of s.prompts) p(`- ${q}`);
    p("");
  }
  if (def.key === "objections") p("_The short answers to each objection are in the next section._", "");
  if (s.tips?.length) {
    p("**Notes for the rep (not read out)**", "");
    for (const t of s.tips) p(`- ${t}`);
    p("");
  }
}

p("---", "", "## If they push back — the short answers", "");
for (const o of OBJ) p(`### ${o.label}`, "", o.response, "");

let group = null;
for (const s of SCRIPTS) {
  if (s.group !== group) {
    group = s.group;
    p("---", "", `## ${GROUP_TITLES[group] || group}`, "");
  }
  p(`### ${s.name}`, "");
  if (s.when) p(`_When:_ ${s.when}`, "");
  if (s.source) p(`_Where these leads come from:_ ${s.source}`, "");
  const labelled = s.lines.some((l) => l.label);
  if (labelled) {
    for (const l of s.lines) p(`**${l.label}**`, "", l.text, "");
  } else {
    s.lines.forEach((l, i) => p(`${i + 1}. ${l.text}`));
    p("");
  }
  if (s.notes.length) {
    p("**Notes for the rep**", "");
    for (const n of s.notes) p(`- ${n}`);
    p("");
  }
}

p(
  "---",
  "",
  "## The call coach — what a Reverse Selling call is scored on",
  "",
  "A second scorecard beside the usual one, only on calls made on this playbook. The usual overall score is computed exactly as before.",
  "",
  "| Move | Points |",
  "|---|---|",
  ...Object.entries(REVERSE_SELLING_WEIGHTS).map(([k, w]) => `| ${COACH[k] || k} | ${w} |`),
  `| **Total** | **${Object.values(REVERSE_SELLING_WEIGHTS).reduce((a, b) => a + b, 0)}** |`,
  "",
  "## The AI phone agent",
  "",
  "FieldQuo's own phone line answers with the same approach: two questions, objection answers that move to the next step, times offered as two choices, the referral question last. Its goal is a demo with a person. It cannot book a time itself — it has one tool, a transfer to a person — so with a transfer number it puts the caller through to someone who books it; without one, it has the caller's choice of time said clearly for the call recording and never promises anyone will ring; with neither, it sends them to the contact page. The trial is mentioned only when the caller asks to start.",
  "",
);

writeFileSync(OUT, out.join("\n"));
console.log(`wrote ${OUT.replace(ROOT + "/", "")} (${out.length} lines)`);
